"""Packs Practical 6 into a private Kaggle GPU script kernel and writes kaggle/a4_p6/.

The kernel unpacks P6_llm_lora.ipynb and a4_metrics.py into /kaggle/working, executes the notebook there with
nbconvert and leaves the executed notebook, results/ and figures/ as kernel output:

    python kaggle_p6.py
    kaggle kernels push -p kaggle/a4_p6
    kaggle kernels status azizabdulin/a4-p6-llm-lora
    kaggle kernels output azizabdulin/a4-p6-llm-lora -p kaggle/a4_p6/output
"""
import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "kaggle" / "a4_p6"
OUT.mkdir(parents=True, exist_ok=True)
files = {name: base64.b64encode((HERE / name).read_bytes()).decode() for name in ("P6_llm_lora.ipynb", "a4_metrics.py")}

(OUT / "run_p6.py").write_text(f'''# Generated by assignment4/kaggle_p6.py — executes Practical 6 on a Kaggle GPU.
import base64, os, subprocess, sys
FILES = {json.dumps(files)}
os.chdir("/kaggle/working")
for name, data in FILES.items():
    open(name, "wb").write(base64.b64decode(data))
for d in ("data", "results", "figures"):
    os.makedirs(d, exist_ok=True)
# the preinstalled peft is used; an old torchao in the image makes peft refuse to wrap layers, and it is not needed here
subprocess.run([sys.executable, "-m", "pip", "uninstall", "-y", "-q", "torchao"], check=False)
r = subprocess.run(["jupyter", "nbconvert", "--to", "notebook", "--execute", "--inplace",
                    "--ExecutePreprocessor.timeout=7200", "P6_llm_lora.ipynb"])
os.remove("a4_metrics.py")
import shutil; shutil.rmtree("__pycache__", ignore_errors=True); shutil.rmtree("data", ignore_errors=True)
sys.exit(r.returncode)
''')
(OUT / "kernel-metadata.json").write_text(json.dumps({
    "id": "azizabdulin/a4-p6-llm-lora", "title": "a4-p6-llm-lora", "code_file": "run_p6.py", "language": "python",
    "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
    "dataset_sources": [], "competition_sources": [], "kernel_sources": []}, indent=2))
print("written", OUT)
